static void *test_malloc(size_t size, void *user_data) {
  if (user_data != NULL) {
    size_t *alloc_count = (size_t *)user_data;
    (*alloc_count)++;
  }
  return malloc(size);
}

static void *test_realloc(void *ptr, size_t size, void *user_data) {
  if (user_data != NULL) {
    size_t *alloc_count = (size_t *)user_data;
    (*alloc_count)++;
  }
  return realloc(ptr, size);
}

static void test_free(void *ptr, void *user_data) {
  if (user_data != NULL) {
    size_t *free_count = (size_t *)user_data;
    (*free_count)++;
  }
  free(ptr);
}

