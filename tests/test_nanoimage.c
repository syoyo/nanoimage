#define CHECK(cond, msg)                                           \
  do {                                                             \
    if (!(cond)) {                                                 \
      fprintf(stderr, "FAIL: %s (line %d)\\n", msg, __LINE__); \
      return 1;                                                    \
    }                                                              \
  } while (0)

static int test_zlib_stored(void) {
  static const unsigned char compressed[] = {
      0x78, 0x01, 0x01, 0x05, 0x00, 0xfa, 0xff, 0x68,
      0x65, 0x6c, 0x6c, 0x6f, 0x06, 0x2c, 0x02, 0x15};
  unsigned char out[16];
  size_t written = 0;
  char err[128] = {0};

  CHECK(ni_zlib_inflate_stored(compressed, sizeof(compressed), out, sizeof(out),
                               &written, err, sizeof(err)),
        err);
  CHECK(written == 5u, "zlib output size");
  CHECK(memcmp(out, "hello", 5u) == 0, "zlib output content");
  return 0;
}

static int test_png_rgba8(void) {
  static const unsigned char png[] = {
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00,
      0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
      0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89,
      0x00, 0x00, 0x00, 0x10, 0x49, 0x44, 0x41, 0x54, 0x78, 0x01, 0x01,
      0x05, 0x00, 0xfa, 0xff, 0x00, 0xff, 0x00, 0x00, 0xff, 0x05, 0x00,
      0x01, 0xff, 0xfa, 0x5c, 0x88, 0xd1, 0x00, 0x00, 0x00, 0x00, 0x49,
      0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};
  ni_image image;
  char err[128] = {0};

  CHECK(ni_load_png_from_memory(png, sizeof(png), &image, err, sizeof(err)), err);
  CHECK(image.width == 1u, "png width");
  CHECK(image.height == 1u, "png height");
  CHECK(image.channels == 4u, "png channels");
  CHECK(image.bit_depth == 8u, "png bit depth");
  CHECK(image.data_size == 4u, "png pixel size");
  CHECK(image.data[0] == 255u && image.data[1] == 0u && image.data[2] == 0u &&
            image.data[3] == 255u,
        "png pixel value");
  ni_image_free(&image);
  return 0;
}

